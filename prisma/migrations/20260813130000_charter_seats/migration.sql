-- Charter seats: the ledger and the lock for 100 numbered, status-only seats.
-- Seeded here AND in ensure-schema.sql (which is what production applies);
-- INSERT OR IGNORE on the primary key makes both replays no-ops.
CREATE TABLE "CharterSeat" (
    "number" INTEGER NOT NULL PRIMARY KEY,
    "status" TEXT NOT NULL DEFAULT 'open',
    "userId" TEXT,
    "stripeSessionId" TEXT,
    "paymentIntentId" TEXT,
    "holdExpiresAt" DATETIME,
    "claimedAt" DATETIME,
    "retiredAt" DATETIME,
    "updatedAt" DATETIME NOT NULL,
    CONSTRAINT "CharterSeat_userId_fkey" FOREIGN KEY ("userId") REFERENCES "User" ("id") ON DELETE SET NULL ON UPDATE CASCADE
);

CREATE UNIQUE INDEX "CharterSeat_stripeSessionId_key" ON "CharterSeat"("stripeSessionId");
CREATE UNIQUE INDEX "CharterSeat_paymentIntentId_key" ON "CharterSeat"("paymentIntentId");
CREATE INDEX "CharterSeat_status_idx" ON "CharterSeat"("status");

ALTER TABLE "User" ADD COLUMN "charterNumber" INTEGER;
ALTER TABLE "User" ADD COLUMN "showCharterNumber" BOOLEAN NOT NULL DEFAULT true;
CREATE UNIQUE INDEX "User_charterNumber_key" ON "User"("charterNumber");

